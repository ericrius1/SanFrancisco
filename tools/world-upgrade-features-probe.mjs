import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { mkdir, writeFile } from 'node:fs/promises';

const base=process.env.SF_PROBE_URL??'http://localhost:5270';
const out='.data/world-upgrade/features';
await mkdir(out,{recursive:true});
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--enable-unsafe-webgpu','--enable-features=WebGPUDeveloperFeatures','--use-angle=metal','--mute-audio']});
const errors=[],requests=[],report={};
let phase='boot';
const feature=url=>/\/tidalChoir\/(?:index|vegetation)\.ts|\/volumetricClouds\.(?:ts|wgsl)|\/traffic\/ambientCity\.ts/.test(url);
const makePage=async(route,index)=>{
 const context=await browser.newContext({viewport:{width:1280,height:800},deviceScaleFactor:1});
 const page=await context.newPage();
 page.on('request',r=>{if(index===0)requests.push({phase,url:r.url(),type:r.resourceType()});});
 page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
 await page.goto(`${base}/?autostart=1&profile&fullfps&${route}`,{waitUntil:'domcontentloaded',timeout:60000});
 await page.waitForFunction(()=>window.__sf?.renderer?.backend?.device&&!window.__sf.worldArrival?.active&&window.__sf.renderIdle(),null,{timeout:180000});
 await page.evaluate(()=>{window.__sf.sky.setTimeOfDay(15);window.__sf.sky.cycleEnabled=false;});
 return page;
};
const moveToPad=async(page,index)=>{
 await page.evaluate(index=>{
  const sf=window.__sf,p=sf.getTidalChoir().pads[index];
  sf.player.teleportTo({x:p.x,y:p.y+0.93,z:p.z,facing:0,mode:'walk'});
 },index);
};
try {
 const first=await makePage('spawn=goldenGate',0);
 await first.waitForTimeout(3000);
 report.boot= requests.filter(r=>feature(r.url));
 assert.equal(report.boot.length,0,'optional feature code must not load at clean boot');
 console.log('PASS clean boot: zero new optional feature requests');
 phase='cloud-activation';
 await first.evaluate(async()=>{const {CLOUD_TUNING}=await import('/src/world/cloudSettings.ts');CLOUD_TUNING.values.enabled=true;});
 await first.waitForFunction(()=>window.__sf.sky.mesh.material.name==='sf-volumetric-clouds',null,{timeout:120000});
 report.cloudActivation=requests.filter(r=>r.phase===phase&&feature(r.url));
 assert.ok(report.cloudActivation.some(r=>r.url.includes('volumetricClouds.ts')));
 phase='cloud-choice';
 await first.evaluate(async()=>{const {CLOUD_TUNING}=await import('/src/world/cloudSettings.ts');CLOUD_TUNING.values.coverage=0.7;});
 await first.waitForTimeout(1500);
 assert.equal(requests.filter(r=>r.phase===phase&&feature(r.url)).length,0,'coverage must not fetch new assets');
 await first.evaluate(async()=>{const {CLOUD_TUNING}=await import('/src/world/cloudSettings.ts');CLOUD_TUNING.values.enabled=false;});
 await first.waitForFunction(()=>window.__sf.sky.mesh.material.name!=='sf-volumetric-clouds');
 console.log('PASS clouds: first-use shader, coverage reuses resources, clear-sky restore');
 phase='choir-activation';
 await first.evaluate(()=>{const sf=window.__sf,x=-4245,z=-5357;sf.player.teleportTo({x,y:sf.map.groundTop(x,z)+0.93,z,facing:0,mode:'walk'});});
 await first.waitForFunction(()=>window.__sf.getTidalChoir?.()&&!window.__sf.worldArrival.active,null,{timeout:180000});
 await first.waitForFunction(()=>window.__sf.siteFoliage.isReady('tidal-choir-garden'),null,{timeout:180000});
 report.choirActivation=requests.filter(r=>r.phase===phase&&feature(r.url));
 assert.ok(report.choirActivation.some(r=>r.url.includes('tidalChoir/index')));
 phase='choir-pad';
 await moveToPad(first,0);
 await first.waitForFunction(()=>window.__sf.getTidalChoir().debugState().localPad===0,null,{timeout:30000});
 await first.mouse.click(640,400);
 await first.waitForTimeout(1500);
 assert.equal(requests.filter(r=>r.phase===phase&&feature(r.url)).length,0);
 const second=await makePage('zone=tidal-choir',1);
 await second.waitForFunction(()=>window.__sf.getTidalChoir?.(),null,{timeout:120000});
 await Promise.all([first,second].map(p=>p.waitForFunction(()=>window.__sf.net.status==='online'&&window.__sf.net.roster.size>=1,null,{timeout:30000})));
 await moveToPad(second,2);
 await Promise.all([first,second].map(p=>p.waitForFunction(()=>window.__sf.getTidalChoir().debugState().activePads===2,null,{timeout:30000})));
 report.duet=await Promise.all([first,second].map(p=>p.evaluate(()=>({choir:window.__sf.getTidalChoir().debugState(),audio:window.__sf.audioEngine.debugState,clock:window.__sf.net.synchronizedTimeMs()}))));
 await first.evaluate(()=>{const y=window.__sf.map.groundTop(-4245,-5385);window.__sfFreeCam([-4216,y+17,-5348],[-4245,y+3,-5385]);});
 await first.waitForTimeout(1000);
 await first.keyboard.press('Tab');
 await first.screenshot({path:`${out}/tidal-choir-duet.png`});
 await first.keyboard.press('Tab');
 await moveToPad(second,0);
 await Promise.all([first,second].map(p=>p.waitForFunction(()=>window.__sf.getTidalChoir().debugState().activePads===1,null,{timeout:30000})));
 report.samePad=await first.evaluate(()=>window.__sf.getTidalChoir().debugState());
 await second.evaluate(()=>{void window.__sf.wakeCity();});
 await second.waitForFunction(()=>window.__sf.tiles.backgroundStreamingDebug.limit>900&&window.__sf.CONFIG.tileLoadRadius>900,null,{timeout:30000});
 report.wake=await second.evaluate(()=>window.__sf.tiles.backgroundStreamingDebug);
 await second.context().close();
 await first.evaluate(()=>{window.__sfFreeCam(null);const sf=window.__sf,x=-4245,z=-5357;sf.player.teleportTo({x,y:sf.map.groundTop(x,z)+0.93,z,facing:0,mode:'walk'});});
 await first.waitForFunction(()=>window.__sf.getTidalChoir().debugState().activePads===0,null,{timeout:30000});
 console.log('PASS Tidal Choir: two real clients, separate voices, shared-pad gain cap, departure');
 phase='departure';
 await first.evaluate(()=>{const sf=window.__sf,x=3900,z=200;sf.player.teleportTo({x,y:sf.map.groundTop(x,z)+0.93,z,facing:0,mode:'walk'});});
 await first.waitForFunction(()=>!window.__sf.getTidalChoir()&&!window.__sf.siteFoliage.isReady('tidal-choir-garden'),null,{timeout:120000});
 report.unloaded=true;
 await first.context().close();
 const city=await makePage('spawn=downtown',2);
 assert.equal(await city.evaluate(()=>window.__sf.getAmbientCity()),null,'stationary street boot stays fleet-free');
 // Actual first use: walk into the street; no query override or forced loader.
 await city.waitForFunction(()=>window.__sf.rings.state()==='settled'&&!window.__sf.worldArrival.active,null,{timeout:120000});
 await city.mouse.click(640,400);
 const startPosition=await city.evaluate(()=>window.__sf.player.position.toArray());
 await city.keyboard.down('KeyW');
 await city.waitForTimeout(4000);
 await city.keyboard.up('KeyW');
 await city.keyboard.down('KeyS');
 await city.waitForTimeout(4000);
 await city.keyboard.up('KeyS');
 console.log('Street walk',JSON.stringify({startPosition,endPosition:await city.evaluate(()=>window.__sf.player.position.toArray())}));
 await city.waitForFunction(()=>{const s=window.__sf.getAmbientCity?.()?.debugState();return s&&s.cars>0&&s.walkers>0;},null,{timeout:150000});
 await city.waitForTimeout(5000);
 report.city=await city.evaluate(()=>window.__sf.getAmbientCity().debugState());
 assert.ok(report.city.cars<=18&&report.city.walkers<=12&&report.city.carDraws<=3);
 await city.screenshot({path:`${out}/city-life.png`});
 console.log('PASS bounded street life:',JSON.stringify(report.city));
 assert.equal(errors.length,0,errors.join('\n'));
 report.ok=true;
} catch(error) {report.ok=false;report.failure=error.stack;throw error;}
finally {await writeFile(`${out}/results.json`,JSON.stringify({...report,errors,requests},null,2));await browser.close();}

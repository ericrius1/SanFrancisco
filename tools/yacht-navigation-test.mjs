import assert from 'node:assert/strict';
import {navigable,moveOnDeck} from '../src/vehicles/yacht/navigation.ts';
assert(!navigable(0,-13,0,false),'closed secret door blocks passage');
assert(navigable(0,-13,0,true),'open door grants passage');
assert(!navigable(3,-5,0,true),'cabin partition blocks passage');
assert(navigable(0,-5,0,true),'central gallery passage remains clear');
assert(!navigable(0,7,2,true),'open pool skylight has a safe railing boundary');
assert(navigable(5.5,7,2,true),'side promenade goes around pool skylight');
assert(!navigable(12,10,0,true),'outer rail keeps visitors on deck');
const p={x:0,y:3.3,z:-12.4};moveOnDeck(p,.1,-.4,0,false);
assert.equal(p.z,-12.4);assert.equal(p.x,.1,'blocked movement slides along the door');
console.log('PASS yacht door, walls, corridors, skylight, railings and sliding collision');
const {yachtEntry}=await import('../src/vehicles/yacht/entry.ts');
const ctx={position:{x:0,y:0,z:0},map:{isWater:(_x,z)=>z<-100,groundHeight:()=>-20,bridgeDeck:()=>-Infinity}};
const destination=yachtEntry(ctx);
assert(destination.z < -144,'the full yacht footprint clears the shoreline');
assert.deepEqual(yachtEntry({...ctx,position:{...destination,y:0}}),destination,'arrival preview and committed entry choose exactly the same point');
assert.deepEqual(ctx.position,{x:0,y:0,z:0},'destination preview is pure');
console.log('PASS yacht full-footprint entry and stable arrival preview');

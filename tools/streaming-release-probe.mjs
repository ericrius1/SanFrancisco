// Verify the built/deployed release and real production chunk request gates.
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { readdir, readFile, mkdir, writeFile } from 'node:fs/promises';
import { acquirePerformanceProbe } from './performance-probe-lock.mjs';
const base = (process.env.SF_PROBE_URL ?? 'http://localhost:8787').replace(/\/$/, '');
const out = process.env.SF_PROBE_OUT ?? '.data/streaming-upgrade/release';
await mkdir(out, { recursive: true });
const files = (await readdir('dist/assets')).filter(f => f.endsWith('.js'));
const chunks = await Promise.all(files.map(async name => ({ name, code: await readFile(`dist/assets/${name}`, 'utf8') })));
const canopy = chunks.filter(c => c.name.startsWith('canopy-'));
const grass = chunks.filter(c => c.code.includes('wildlands_grass'));
const flower = chunks.filter(c => c.name.startsWith('flowerRing-'));
assert.equal(canopy.length, 1, 'canopy has its own production chunk');
assert.equal(grass.length, 1, 'groundcover has a separately identifiable production chunk');
assert.ok(flower.length > 0, 'flowers retain a separate production chunk');
assert.notEqual(canopy[0].name, grass[0].name, 'canopy and grass are split');
const remoteHtml = await (await fetch(`${base}/`, { cache: 'no-store' })).text();
const localHtml = await readFile('dist/index.html', 'utf8');
const entry = localHtml.match(/src="(\/assets\/[^\"]+\.js)"/)[1];
assert.ok(remoteHtml.includes(entry), 'server serves this exact built entry');
assert.equal((await fetch(`${base}/healthz`)).status, 200, 'production health');
const release = await acquirePerformanceProbe();
const browser = await chromium.launch({ executablePath: process.env.CHROME_BIN ?? '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--enable-unsafe-webgpu', '--enable-gpu', '--use-angle=metal', '--mute-audio'] });
const report = { entry, chunks: { canopy: canopy[0].name, grass: grass[0].name, flowers: flower.map(c => c.name) }, requests: [], errors: [], sockets: [] };
let phase = 'boot';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, serviceWorkers: 'block' });
  page.on('request', r => report.requests.push({ phase, url: r.url() }));
  page.on('pageerror', e => report.errors.push(e.message));
  page.on('console', m => { if (m.type() === 'error') report.errors.push(m.text()); });
  page.on('websocket', ws => ws.on('framereceived', () => { if (!report.sockets.includes(ws.url())) report.sockets.push(ws.url()); }));
  const requested = (names, at = phase) => report.requests.filter(r => r.phase === at && names.some(n => r.url.includes(`/assets/${n}`)));
  const leafRequests = () => report.requests.filter(r => r.url.includes('/native-foliage/'));
  await page.goto(`${base}/?autostart=1&profile=1&spawn=downtown`, { waitUntil: 'domcontentloaded', timeout: 90000 });
  await page.waitForFunction(() => window.__sf?.rings?.state() === 'settled' && !window.__sf.worldArrival.active, null, { timeout: 180000 });
  assert.equal(requested([...canopy, ...grass, ...flower].map(c => c.name)).length, 0, 'zero distant vegetation chunks at boot');
  assert.equal(leafRequests().length, 0, 'zero near textures at boot');
  assert.ok(report.sockets.some(u => u.endsWith('/ws')), 'multiplayer relay exchanges frames');
  console.log(JSON.stringify({ phase, entry, errors: report.errors.length }));
  phase = 'canopy-approach';
  await page.evaluate(() => window.__sf.player.teleportTo({ x: -3500, y: 250, z: 3850, facing: 0, mode: 'drone' }));
  await page.waitForFunction(() => window.__sf.wildlandsCanopy?.trees.group.parent && !window.__sf.worldArrival.active, null, { timeout: 180000 });
  assert.equal(requested(canopy.map(c => c.name)).length, 1, 'first approach requests canopy exactly once');
  assert.equal(requested([...grass, ...flower].map(c => c.name)).length, 0, 'first approach leaves grass/flowers asleep');
  assert.equal(leafRequests().length, 0, 'distant canopy requests no near textures');
  assert.ok(await page.evaluate(() => !window.__sf.wildlands), 'canopy visible before groundcover exists');
  console.log(JSON.stringify({ phase, nearTextureRequests: leafRequests().length }));
  phase = 'park-flight';
  await page.evaluate(() => window.__sf.player.teleportTo({ x: -3500, y: 250, z: 2300, facing: 0, mode: 'drone' }));
  await page.waitForFunction(() => window.__sf.wildlands?.trees.group.parent && !window.__sf.worldArrival.active, null, { timeout: 180000 });
  assert.equal(requested(grass.map(c => c.name)).length, 1, 'close approach requests groundcover once');
  assert.equal(requested(canopy.map(c => c.name)).length, 0, 'subsequent approach reuses canopy chunk');
  report.flight = await page.evaluate(() => ({ nearActive: window.__sf.wildlands.trees.stats.nearActive(), sameForest: window.__sf.wildlands.trees === window.__sf.wildlandsCanopy.trees, backend: window.__sf.renderer.backend.constructor.name }));
  assert.ok(report.flight.sameForest, 'single shared forest owner');
  assert.equal(report.flight.nearActive, 0, 'altitude prevents close tree allocation');
  assert.equal(leafRequests().length, 0, 'park flight still requests no near textures');
  await page.screenshot({ path: `${out}/park-flight.png` });
  assert.equal(report.errors.length, 0, report.errors.join('\n'));
  console.log(JSON.stringify({ ok: true, phase, ...report.flight }));
} finally {
  await writeFile(`${out}/report.json`, JSON.stringify(report, null, 2));
  await browser.close(); await release();
}
